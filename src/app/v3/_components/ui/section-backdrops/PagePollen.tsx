"use client";

import { usePathname } from "next/navigation";
import Pollen from "./Pollen";

/**
 * Фон секций всей ветки — вариант F «Пыльца», выбранный заказчиком
 * в лаборатории /v3/section-lab.
 *
 * Один слой на страницу, а не по слою в каждую секцию: движение везде
 * одинаковое, а платим за него один раз. Слой закреплён на экране и
 * лежит ниже всего контента (тот поднят на z-10 в layout), поэтому под
 * первым экраном с фотографией и под картой посёлка его попросту не
 * видно — светлячки живут на пустом полотне между блоками.
 *
 * На слабых устройствах и при системной настройке «меньше движения»
 * Pollen сам возвращает пустоту.
 */
export default function PagePollen() {
  // В лаборатории общий фон только мешал бы сравнению: там свой
  // переключатель, и вариант «0 · Без фона» обязан быть пустым.
  if (usePathname()?.startsWith("/v3/section-lab")) return null;

  return (
    <div aria-hidden="true" className="pointer-events-none fixed inset-0 z-0 overflow-hidden">
      <Pollen />
    </div>
  );
}
